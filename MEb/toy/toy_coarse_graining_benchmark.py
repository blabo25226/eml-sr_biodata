#!/usr/bin/env python3
"""
toy_coarse_graining_benchmark.py

Fast toy benchmark: low-dimensional EML cascades coarse-grain a 50-state
activation/adaptation network.

The high-dimensional system is a simple mass-action-like reaction cascade with
20 fast activation states and 30 slow inhibitory states. It is not generated by
EML. The reduced model uses a fixed EML cascade to generate sequential hidden
states z_1,...,z_K, then fits a linear readout on training time points:

    y_K(t) = beta_0 + sum_{j=1}^K beta_j z_j(t).

This avoids arbitrary hand-picked output weights: beta_j are fitted by weighted
least squares. It also makes K a genuine coarse-graining depth: how many
sequential EML hidden states are needed to approximate the 50-state input-output
map?

The benchmark is deliberately methodological. It does not claim that the hidden
states recover the true microscopic species; it tests whether an EML-generated
low-dimensional basis can approximate the output of a much larger dynamical
system.

Example:
    python toy_coarse_graining_benchmark.py --out-prefix toy_eml_coarse --Kmax 10
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy.integrate import solve_ivp
from scipy.optimize import least_squares


@dataclass
class ToyParams:
    n_A: int = 20
    n_I: int = 30
    tmax: float = 80.0
    ntime: int = 241

    k_R: float = 0.45

    k_on_A: float = 2.4
    k_off_A: float = 0.55
    tau_A: float = 0.28

    k_on_I: float = 0.75
    k_off_I: float = 0.08
    tau_I: float = 0.75

    y0: float = 0.0
    A_amp: float = 1.6
    I_amp: float = 1.25
    K_A: float = 0.18
    K_I: float = 0.22

    noise_sd: float = 0.015
    random_seed: int = 1


def R_of_t(t, k):
    return 1.0 - np.exp(-k * np.asarray(t))


def simulate_high_dim_network(p: ToyParams) -> pd.DataFrame:
    n = p.n_A + p.n_I
    t_eval = np.linspace(0, p.tmax, p.ntime)

    def rhs(t, x):
        A = x[:p.n_A]
        I = x[p.n_A:]
        R = float(R_of_t(t, p.k_R))
        dx = np.zeros_like(x)

        dx[0] = p.k_on_A * R * (1 - A[0]) - p.k_off_A * A[0]
        for i in range(1, p.n_A):
            dx[i] = (A[i - 1] - A[i]) / p.tau_A

        dx[p.n_A] = p.k_on_I * R * (1 - I[0]) - p.k_off_I * I[0]
        for i in range(1, p.n_I):
            dx[p.n_A + i] = (I[i - 1] - I[i]) / p.tau_I

        return dx

    sol = solve_ivp(rhs, (0, p.tmax), np.zeros(n), t_eval=t_eval,
                    method="LSODA", rtol=1e-8, atol=1e-10)
    if not sol.success:
        raise RuntimeError(sol.message)

    A_end = sol.y[p.n_A - 1]
    I_end = sol.y[p.n_A + p.n_I - 1]
    y_clean = p.y0 + p.A_amp * A_end/(p.K_A + A_end) - p.I_amp * I_end/(p.K_I + I_end)

    rng = np.random.default_rng(p.random_seed)
    y_obs = y_clean + rng.normal(0, p.noise_sd, size=len(t_eval))
    sem = np.full_like(y_clean, p.noise_sd)

    return pd.DataFrame({
        "time": t_eval,
        "R": R_of_t(t_eval, p.k_R),
        "A_end": A_end,
        "I_end": I_end,
        "y_clean": y_clean,
        "y_obs": y_obs,
        "sem": sem,
    })


def train_valid_split(n):
    idx = np.arange(n)
    valid = idx % 4 == 1
    train = ~valid
    train[0] = True
    valid[0] = False
    return train, valid


def centered_gate(x, a, b, c):
    xp = np.maximum(c + x, 1e-9)
    return xp**a - b*x - c**a


def first_order_filter(t, drive, tau):
    z = np.zeros_like(t)
    for i in range(1, len(t)):
        dt = t[i] - t[i-1]
        decay = np.exp(-dt/tau)
        dmid = 0.5*(drive[i-1] + drive[i])
        z[i] = dmid + (z[i-1] - dmid)*decay
    return z


def make_eml_states(t, Kmax, k_fit, tau_scale):
    """
    Generate z_1,...,z_Kmax from a fixed centered EML cascade.
    Parameters were chosen to produce progressively delayed pulses from a
    monotone input; the readout coefficients are fitted, not chosen.
    """
    R = R_of_t(t, k_fit)
    z_prev = R
    states = []
    for j in range(Kmax):
        a = 0.45 + 0.035*j
        b = 1.00 if j == 0 else 0.42 - 0.015*min(j, 10)
        c = 1e-6 if j == 0 else 0.08
        tau = tau_scale * (1.0 + 0.55*j)
        drive = centered_gate(z_prev, a, b, c)
        z = first_order_filter(t, drive, tau)
        states.append(z)
        z_prev = z
    return np.asarray(states)


def weighted_linear_fit(X, y, sem, train):
    w = 1.0 / np.maximum(sem, np.median(sem[sem > 0])*0.25)
    Xw = X[train] * w[train, None]
    yw = y[train] * w[train]
    coef, *_ = np.linalg.lstsq(Xw, yw, rcond=None)
    return coef


def fit_eml_basis(t, y, sem, Kmax):
    train, valid = train_valid_split(len(t))
    rows = []
    predictions = {}
    states_by_key = {}

    # Grid over two global hyperparameters. This is fast and explicit.
    k_grid = np.linspace(0.15, 0.80, 18)
    tau_grid = np.linspace(0.5, 5.5, 20)

    for K in range(1, Kmax+1):
        best = None
        for k_fit in k_grid:
            for tau_scale in tau_grid:
                states = make_eml_states(t, K, k_fit, tau_scale)
                X = np.column_stack([np.ones_like(t), states[:K].T])
                coef = weighted_linear_fit(X, y, sem, train)
                pred = X @ coef
                w = 1.0 / np.maximum(sem, np.median(sem[sem > 0])*0.25)
                train_wmse = np.mean(((pred[train]-y[train])*w[train])**2)
                valid_wmse = np.mean(((pred[valid]-y[valid])*w[valid])**2)
                # Tiny ridge-like complexity penalty for tie-breaking only.
                score = valid_wmse + 0.002*K
                if best is None or score < best["score"]:
                    best = dict(K=K, k_fit=k_fit, tau_scale=tau_scale, coef=coef,
                                pred=pred, states=states[:K], train_wmse=train_wmse,
                                valid_wmse=valid_wmse, score=score)
        p   = K + 3          # K+1 readout coefficients + k_fit + tau_scale
        N_T = int(np.sum(train))
        train_chi2 = best["train_wmse"] * N_T
        aic = N_T * np.log(train_chi2 / N_T) + 2 * p
        bic = N_T * np.log(train_chi2 / N_T) + p * np.log(N_T)
        rows.append({k: best[k] for k in ["K","k_fit","tau_scale","train_wmse","valid_wmse","score"]} |
                    {"n_states": K, "n_parameters": p, "N_T": N_T,
                     "train_chi2": train_chi2, "AIC": aic, "BIC": bic,
                     "coefficients": "; ".join(f"beta{i}={v:.6g}" for i,v in enumerate(best["coef"]))})
        predictions[K] = best["pred"]
        states_by_key[K] = best["states"]

    return pd.DataFrame(rows), predictions, states_by_key


def predict_hill(t, p):
    y0, A, Kd, h, k = p
    R = R_of_t(t, k)
    return y0 + A * R**h/(Kd**h + R**h + 1e-12)


def fit_hill(t, y, sem):
    train, valid = train_valid_split(len(t))
    w = 1.0 / np.maximum(sem, np.median(sem[sem > 0])*0.25)
    y0 = y[0]
    amp = max(1, y.max()-y.min())
    starts = [
        [y0, amp, 0.5, 2, 0.4],
        [y0, -amp, 0.5, 2, 0.4],
        [y0, amp, 2, 5, 0.2],
        [y0, -amp, 2, 5, 0.2],
    ]
    lo = np.array([-5,-20,1e-4,0.05,0.01])
    hi = np.array([5,20,100,20,5])
    best = None
    for s in starts:
        def res(p):
            return (predict_hill(t,p)[train]-y[train])*w[train]
        fit = least_squares(res, np.asarray(s), bounds=(lo,hi), max_nfev=5000)
        train_wmse = np.mean(res(fit.x)**2)
        pred = predict_hill(t, fit.x)
        valid_wmse = np.mean(((pred[valid]-y[valid])*w[valid])**2)
        if best is None or valid_wmse < best["valid_wmse"]:
            best = dict(pred=pred, params=fit.x, train_wmse=train_wmse, valid_wmse=valid_wmse)
    p_hill = len(best["params"])   # 5: y0, A, Kd, h, k
    N_T    = int(np.sum(train))
    train_chi2 = best["train_wmse"] * N_T
    best["train_chi2"] = train_chi2
    best["N_T"]  = N_T
    best["AIC"]  = N_T * np.log(train_chi2 / N_T) + 2 * p_hill
    best["BIC"]  = N_T * np.log(train_chi2 / N_T) + p_hill * np.log(N_T)
    best["n_parameters"] = p_hill
    return best


def save_outputs(data, eml_summary, eml_predictions, states_by_key, hill, out_prefix, plot_format):
    data_path    = out_prefix.with_name(out_prefix.name + "_synthetic_data.csv")
    summary_path = out_prefix.with_name(out_prefix.name + "_fit_summary.csv")
    pred_path    = out_prefix.with_name(out_prefix.name + "_predictions.csv")
    plot_path    = out_prefix.with_name(out_prefix.name + f"_benchmark.{plot_format}")
    svg_path     = out_prefix.with_name(out_prefix.name + "_benchmark.svg")
    aic_bic_path = out_prefix.with_name(out_prefix.name + "_aic_bic.csv")

    data.to_csv(data_path, index=False)

    hill_row = pd.DataFrame([{
        "K": 0, "k_fit": hill["params"][4], "tau_scale": np.nan,
        "train_wmse": hill["train_wmse"], "valid_wmse": hill["valid_wmse"],
        "score": hill["valid_wmse"], "n_states": 0,
        "n_parameters": hill["n_parameters"], "N_T": hill["N_T"],
        "train_chi2": hill["train_chi2"], "AIC": hill["AIC"], "BIC": hill["BIC"],
        "coefficients": "; ".join(f"p{i}={v:.6g}" for i,v in enumerate(hill["params"]))
    }])
    summary = pd.concat([hill_row, eml_summary], ignore_index=True).sort_values("valid_wmse")

    # AIC/BIC table with delta columns
    aic_bic = summary[["K", "n_parameters", "N_T", "train_chi2",
                        "valid_wmse", "AIC", "BIC"]].copy()
    aic_bic["DeltaAIC"] = aic_bic["AIC"] - aic_bic["AIC"].min()
    aic_bic["DeltaBIC"] = aic_bic["BIC"] - aic_bic["BIC"].min()
    aic_bic = aic_bic.sort_values("K")
    aic_bic.to_csv(aic_bic_path, index=False)
    summary.to_csv(summary_path, index=False)

    rows = []
    for t,yc,yo,sem,hp in zip(data['time'], data['y_clean'], data['y_obs'], data['sem'], hill["pred"]):
        rows.append({"model":"Hill", "K":0, "time":t, "y_clean":yc, "y_obs":yo, "sem":sem, "prediction":hp})
    for K,pred in eml_predictions.items():
        for t,yc,yo,sem,pr in zip(data['time'], data['y_clean'], data['y_obs'], data['sem'], pred):
            rows.append({"model":f"EML basis K={K}", "K":K, "time":t, "y_clean":yc, "y_obs":yo, "sem":sem, "prediction":pr})
    pd.DataFrame(rows).to_csv(pred_path, index=False)

    t = data['time'].to_numpy()

    _FS     = 9     # axis labels / tick labels (~10 pt PRE body at 7-inch figure width)
    _FS_LEG = 7.5   # legend entries
    _FS_PNL = 11    # panel labels (a)–(d), slightly larger than body text
    _LW_REF = 0.6   # y = 0 reference line width

    with plt.rc_context({'text.usetex': True, 'font.family': 'serif',
                         'font.size': _FS, 'axes.labelsize': _FS,
                         'xtick.labelsize': _FS, 'ytick.labelsize': _FS}):
        fig, axes = plt.subplots(2, 2, figsize=(7.0, 5.2))

        ax = axes[0, 0]
        ax.plot(t, data['R'], label="Input R(t)")
        ax.plot(t, data['A_end'], label="Fast branch")
        ax.plot(t, data['I_end'], label="Slow branch")
        ax.set_title("50-state activation/adaptation network", fontsize=_FS)
        ax.set_xlabel("Time")
        ax.set_ylabel("State")
        ax.axhline(0, color='k', linewidth=_LW_REF, zorder=0)
        ax.legend(frameon=False, fontsize=_FS_LEG)

        ax = axes[0, 1]
        ax.plot(t, data['y_clean'], linewidth=2.0, label="50-state output")
        ax.errorbar(t[::6], data['y_obs'].to_numpy()[::6],
                    yerr=data['sem'].to_numpy()[::6],
                    fmt='o', ms=2.5, capsize=1.5, label="Observations")
        ax.plot(t, hill["pred"], '--', label="Hill")
        for K in [1, 2, 3, 5, 10]:
            if K in eml_predictions:
                ax.plot(t, eml_predictions[K], label=f"EML K={K}")
        ax.set_title("Reduced fits", fontsize=_FS)
        ax.set_xlabel("Time")
        ax.set_ylabel("Output")
        ax.axhline(0, color='k', linewidth=_LW_REF, zorder=0)
        ax.legend(frameon=False, fontsize=_FS_LEG)

        ax = axes[1, 0]
        df = pd.concat([hill_row, eml_summary], ignore_index=True).sort_values("K")
        ax.plot(df.K, df.valid_wmse, marker='o', markersize=4)
        ax.set_yscale("log")
        ax.set_xlabel("Reduced depth K (Hill shown as K=0)")
        ax.set_ylabel("Held-out weighted MSE")
        ax.set_title("Predictive error vs. EML depth", fontsize=_FS)

        ax = axes[1, 1]
        bestK = int(eml_summary.sort_values("valid_wmse").iloc[0].K)
        for j, z in enumerate(states_by_key[bestK], 1):
            ax.plot(t, z, label=f"$z_{{{j}}}$")
        ax.set_title(f"EML hidden states, best K={bestK}", fontsize=_FS)
        ax.set_xlabel("Time")
        ax.set_ylabel("State")
        ax.axhline(0, color='k', linewidth=_LW_REF, zorder=0)
        ax.legend(frameon=False, fontsize=_FS_LEG)

        # Panel labels (a)–(d): outside the plot area at the top-left corner.
        # y=1.04 sits just above the top spine; clip_on=False prevents clipping
        # at the axes boundary.  x=0 aligns with the left edge of the plot frame,
        # which is always to the right of y-tick labels and the y-axis label.
        for ax, lbl in zip([axes[0, 0], axes[0, 1], axes[1, 0], axes[1, 1]],
                           ['(a)', '(b)', '(c)', '(d)']):
            ax.text(0.0, 1.04, lbl, transform=ax.transAxes,
                    fontsize=_FS_PNL, va='bottom', ha='left', clip_on=False)

        fig.tight_layout(pad=0.8)
        fig.savefig(plot_path, bbox_inches='tight')
        fig.savefig(svg_path,  bbox_inches='tight')
    plt.close(fig)

    return data_path, summary_path, pred_path, plot_path, svg_path, aic_bic_path, summary, aic_bic


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--out-prefix",type=Path,default=Path("toy_eml_coarse"))
    ap.add_argument("--Kmax",type=int,default=10)
    ap.add_argument("--noise-sd",type=float,default=0.015)
    ap.add_argument("--seed",type=int,default=1)
    ap.add_argument("--plot-format",choices=["png","pdf"],default="png")
    args=ap.parse_args()

    params=ToyParams(noise_sd=args.noise_sd,random_seed=args.seed)
    data=simulate_high_dim_network(params)
    t=data.time.to_numpy(); y=data['y_obs'].to_numpy(); sem=data['sem'].to_numpy()

    hill=fit_hill(t,y,sem)
    eml_summary, eml_predictions, states_by_key = fit_eml_basis(t,y,sem,args.Kmax)

    args.out_prefix.parent.mkdir(parents=True,exist_ok=True)
    data_path, summary_path, pred_path, plot_path, svg_path, aic_bic_path, summary, aic_bic = \
        save_outputs(data, eml_summary, eml_predictions, states_by_key, hill,
                     args.out_prefix, args.plot_format)

    print("\nFit summary sorted by held-out weighted MSE:")
    print(summary[["K","n_states","n_parameters","valid_wmse","train_wmse"]].to_string(index=False))
    print(f"\nSaved synthetic data: {data_path}")
    print(f"Saved summary:        {summary_path}")
    print(f"Saved predictions:    {pred_path}")
    print(f"Saved plot:           {plot_path}")
    print(f"Saved SVG:            {svg_path}")
    print(f"Saved AIC/BIC table:  {aic_bic_path}")

    # --- Values for figure caption ---
    p = hill["params"]
    print("\n=== Hill fit (for caption) ===")
    print(f"  y0={p[0]:.4g}, A={p[1]:.4g}, Kd={p[2]:.4g}, h={p[3]:.3g}, k={p[4]:.4g}")
    print(f"  Train wMSE = {hill['train_wmse']:.4g},  Validation wMSE = {hill['valid_wmse']:.4g}")
    print(f"  AIC = {hill['AIC']:.2f},  BIC = {hill['BIC']:.2f}")
    print("\n=== EML basis fits — AIC/BIC by depth K ===")
    print(aic_bic[["K","n_parameters","N_T","train_chi2",
                   "valid_wmse","AIC","BIC","DeltaAIC","DeltaBIC"]].to_string(index=False))


if __name__=="__main__":
    main()
